const backgroundMusic = new Audio("Taweel Al Shawq.MP3.mp3");
backgroundMusic.loop = true;
backgroundMusic.volume = 0.35;

const musicButton = document.getElementById("musicToggle");
const musicLabel = document.getElementById("musicLabel");

musicButton.addEventListener("click", async () => {
  try {
    if (backgroundMusic.paused) {
      await backgroundMusic.play();
      musicButton.setAttribute("aria-pressed", "true");
      musicButton.title = "Matikan musik latar";
      musicLabel.textContent = "Musik: hidup";
    } else {
      backgroundMusic.pause();
      musicButton.setAttribute("aria-pressed", "false");
      musicButton.title = "Nyalakan musik latar";
      musicLabel.textContent = "Musik: mati";
    }
  } catch (error) {
    musicLabel.textContent = "Musik gagal diputar";
    console.error("Musik tidak dapat diputar:", error);
  }
});

