const grid = document.getElementById("letterGrid");
const filters = document.getElementById("categoryFilters");
const modal = document.getElementById("letterModal");
const modalTitle = document.getElementById("modalTitle");
const modalCategory = document.getElementById("modalCategory");
const modalBody = document.getElementById("modalBody");
let currentLetter = null;
let activeCategory = "all";

function renderLetters(category = "all") {
  activeCategory = category;
  const filtered = category === "all" ? letters : letters.filter(letter => letter.category === category);
  grid.innerHTML = "";
  document.getElementById("noResults").hidden = filtered.length !== 0;
  filtered.forEach(letter => {
    const card = document.createElement("article");
    card.className = "letter-card";
    card.tabIndex = 0;
    card.setAttribute("role", "button");
    card.setAttribute("aria-label", `Buka surat: ${letter.title}`);
    card.innerHTML = `
      <div class="card-top"><span class="card-category">${letter.categoryLabel}</span><span class="card-number">No. ${String(letter.id).padStart(2, "0")}</span></div>
      <div class="card-icon" aria-hidden="true">${letter.icon}</div>
      <h3>${letter.title}</h3>
      <p>${letter.excerpt}</p>
      <div class="card-open"><span>BACA SURAT</span><span aria-hidden="true">↗</span></div>`;
    card.addEventListener("click", () => openLetter(letter));
    card.addEventListener("keydown", event => {
      if (event.key === "Enter" || event.key === " ") { event.preventDefault(); openLetter(letter); }
    });
    grid.appendChild(card);
  });
  filters.querySelectorAll(".filter-chip").forEach(button => {
    const isActive = button.dataset.category === category;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function openLetter(letter) {
  currentLetter = letter;
  modalCategory.textContent = letter.categoryLabel;
  modalTitle.textContent = letter.salutation;
  modalBody.innerHTML = "";
  letter.body.split("\n\n").forEach(paragraph => {
    const p = document.createElement("p");
    p.textContent = paragraph;
    modalBody.appendChild(p);
  });
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  document.getElementById("copyFeedback").textContent = "";
  document.getElementById("modalClose").focus();
}

function closeLetter() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

filters.addEventListener("click", event => {
  const button = event.target.closest("[data-category]");
  if (button) renderLetters(button.dataset.category);
});
document.getElementById("randomLetter").addEventListener("click", () => {
  const choices = activeCategory === "all" ? letters : letters.filter(item => item.category === activeCategory);
  openLetter(choices[Math.floor(Math.random() * choices.length)]);
});
document.getElementById("modalRandom").addEventListener("click", () => {
  const choices = letters.filter(item => item.id !== (currentLetter && currentLetter.id));
  openLetter(choices[Math.floor(Math.random() * choices.length)]);
});
document.getElementById("modalClose").addEventListener("click", closeLetter);
document.getElementById("modalBackdrop").addEventListener("click", closeLetter);
document.addEventListener("keydown", event => { if (event.key === "Escape" && modal.classList.contains("open")) closeLetter(); });

document.getElementById("copyLetter").addEventListener("click", async () => {
  if (!currentLetter) return;
  const text = `${currentLetter.salutation}\n\n${currentLetter.body}\n\nDengan tulus,\nseseorang yang mendoakanmu`;
  const feedback = document.getElementById("copyFeedback");
  try {
    await navigator.clipboard.writeText(text);
    feedback.textContent = "Surat berhasil disalin. Kamu bisa membagikannya dengan seseorang. ♡";
  } catch {
    const area = document.createElement("textarea");
    area.value = text;
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const copied = document.execCommand("copy");
    area.remove();
    feedback.textContent = copied ? "Surat berhasil disalin. ♡" : "Salin teks surat secara manual dari jendela ini, ya.";
  }
});

